import Foundation
import CryptoKit

public struct ClipboardRepresentation: Codable, Sendable, Equatable {
    public let type: String
    public let data: Data
    public init(type: String, data: Data) { self.type = type; self.data = data }
}

public struct ClipboardPayloadItem: Codable, Sendable, Equatable {
    public let representations: [ClipboardRepresentation]
    public init(representations: [ClipboardRepresentation]) { self.representations = representations }
}

public struct ClipboardPayload: Codable, Sendable, Equatable {
    public let items: [ClipboardPayloadItem]
    public init(items: [ClipboardPayloadItem]) { self.items = items }
    public var byteCount: Int { items.reduce(0) { $0 + $1.representations.reduce(0) { $0 + $1.data.count } } }
    public var fingerprint: String {
        var hash = SHA256()
        func append(_ data: Data) {
            var size = UInt64(data.count).bigEndian
            withUnsafeBytes(of: &size) { hash.update(data: Data($0)) }
            hash.update(data: data)
        }
        append(Data(String(items.count).utf8))
        for item in items {
            append(Data(String(item.representations.count).utf8))
            for representation in item.representations.sorted(by: { $0.type < $1.type }) {
                append(Data(representation.type.utf8)); append(representation.data)
            }
        }
        return hash.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

public struct ClipboardHistoryRecord: Codable, Sendable, Identifiable, Equatable {
    public enum Kind: String, Codable, Sendable { case text, image, file }
    public let id: String
    public let kind: Kind
    public let title: String
    public let searchableText: String
    public var sourceBundleID: String?
    public var sourceName: String?
    public var copiedAt: Date
    public var favorite: Bool
    public let byteCount: Int
    public let storedBytes: Int
    public let itemCount: Int
    public var imageLabel: String { "图片" }
}

public struct ClipboardHistoryLimits: Sendable {
    public let count: Int
    public let retention: TimeInterval
    public let diskBytes: Int
    public let itemBytes: Int
    public init(count: Int = 200, retention: TimeInterval = 7 * 86_400,
                diskBytes: Int = 256 * 1_024 * 1_024, itemBytes: Int = 64 * 1_024 * 1_024) {
        self.count = max(1, min(count, 2_000)); self.retention = max(3_600, retention)
        self.diskBytes = max(1_024, diskBytes); self.itemBytes = max(1, min(itemBytes, 64 * 1_024 * 1_024))
    }
}

public enum ClipboardHistoryError: LocalizedError, Sendable {
    case tooLarge, empty, missing, invalidIndex, favoritesFillQuota
    public var errorDescription: String? {
        switch self {
        case .tooLarge: "这条剪贴板内容超过大小上限。"
        case .empty: "剪贴板中没有支持的内容。"
        case .missing: "这条记录的数据已丢失或损坏。"
        case .invalidIndex: "无法读取剪贴板历史索引，已有数据已保留。"
        case .favoritesFillQuota: "收藏已占满历史容量，请取消部分收藏或提高上限。"
        }
    }
}

public enum ClipboardPrivacy {
    public static let ownMarker = "theboringteam.boringnotch.clipboard-origin"
    public static let ignoredTypes: Set<String> = [
        ownMarker, "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType", "net.antelle.keeweb", "com.typeit4me.clipping",
        "Pasteboard generator type"
    ]
    public static let ignoredApps: Set<String> = [
        "com.apple.Passwords", "com.apple.keychainaccess", "com.1password.1password",
        "com.agilebits.onepassword7", "com.agilebits.onepassword-osx", "com.bitwarden.desktop",
        "org.keepassxc.keepassxc", "com.dashlane.Dashlane", "com.enpass.Enpass"
    ]
    public static func shouldIgnore(types: Set<String>, sourceBundleID: String?, extraApps: Set<String> = []) -> Bool {
        !types.isDisjoint(with: ignoredTypes) || sourceBundleID.map { ignoredApps.union(extraApps).contains($0) } == true
    }
}

/// A bounded metadata index is atomic and small; original pasteboard bytes live in separate binary
/// payload files. One actor serializes all mutations, so a reload never sees half a snapshot.
public actor ClipboardHistory {
    private struct Index: Codable { let version: Int; let records: [ClipboardHistoryRecord] }
    private let directory: URL
    private var records: [ClipboardHistoryRecord] = []
    private var loaded = false
    private let indexLimit = 24 * 1_024 * 1_024
    private let payloadLimit = 68 * 1_024 * 1_024

    public init(directory: URL) { self.directory = directory }

    private var indexURL: URL { directory.appendingPathComponent("history.json") }
    private func payloadURL(_ id: String) -> URL { directory.appendingPathComponent(id + ".clipboard") }
    private func validID(_ id: String) -> Bool { id.count == 64 && id.allSatisfy { $0.isHexDigit && !$0.isUppercase } }
    /// Read through a bounded handle, so an external replacement/growing file between stat and read
    /// cannot turn a metadata limit check into an unbounded allocation.
    private func readBounded(_ url: URL, maxBytes: Int) throws -> Data {
        let handle = try FileHandle(forReadingFrom: url)
        defer { try? handle.close() }
        var result = Data()
        while true {
            let allowance = min(65_536, maxBytes - result.count + 1)
            guard let chunk = try handle.read(upToCount: allowance), !chunk.isEmpty else { return result }
            result.append(chunk)
            guard result.count <= maxBytes else { throw ClipboardHistoryError.tooLarge }
        }
    }
    private func loadIfNeeded() throws {
        guard !loaded else { return }
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true,
                                                 attributes: [.posixPermissions: 0o700])
        if FileManager.default.fileExists(atPath: indexURL.path) {
            guard (try indexURL.resourceValues(forKeys: [.fileSizeKey]).fileSize ?? 0) <= indexLimit else {
                throw ClipboardHistoryError.invalidIndex
            }
            let index: Index
            do { index = try JSONDecoder().decode(Index.self, from: readBounded(indexURL, maxBytes: indexLimit)) }
            catch { throw ClipboardHistoryError.invalidIndex }
            guard index.version == 1, index.records.count <= 2_000,
                  Set(index.records.map(\.id)).count == index.records.count,
                  index.records.allSatisfy({ validID($0.id) && $0.storedBytes > 0 && $0.storedBytes <= payloadLimit
                    && $0.byteCount >= 0 && $0.byteCount <= 64 * 1_024 * 1_024 }) else {
                throw ClipboardHistoryError.invalidIndex
            }
            records = index.records
        }
        loaded = true
        try removeOrphans()
    }
    private func save(_ updated: [ClipboardHistoryRecord]) throws {
        let data = try JSONEncoder().encode(Index(version: 1, records: updated))
        guard data.count <= indexLimit else { throw ClipboardHistoryError.tooLarge }
        try data.write(to: indexURL, options: .atomic)
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: indexURL.path)
        records = updated
    }
    private func removeOrphans() throws {
        let live = Set(records.map(\.id))
        for url in try FileManager.default.contentsOfDirectory(at: directory, includingPropertiesForKeys: nil) {
            let id = url.deletingPathExtension().lastPathComponent
            if url.pathExtension == "clipboard", validID(id), !live.contains(id) {
                try FileManager.default.removeItem(at: url)
            }
        }
    }
    private func retained(_ input: [ClipboardHistoryRecord], limits: ClipboardHistoryLimits, now: Date) throws -> [ClipboardHistoryRecord] {
        var result = input.filter { $0.favorite || now.timeIntervalSince($0.copiedAt) < limits.retention }
            .sorted { $0.copiedAt > $1.copiedAt }
        var usedBytes = try result.reduce(0) { total, record in
            let (next, overflow) = total.addingReportingOverflow(record.storedBytes)
            guard record.storedBytes > 0, !overflow else { throw ClipboardHistoryError.invalidIndex }
            return next
        }
        while result.count > limits.count || usedBytes > limits.diskBytes {
            guard let index = result.lastIndex(where: { !$0.favorite }) else { throw ClipboardHistoryError.favoritesFillQuota }
            usedBytes -= result.remove(at: index).storedBytes
        }
        return result
    }
    public func load(limits: ClipboardHistoryLimits = .init(), now: Date = Date()) throws -> [ClipboardHistoryRecord] {
        try loadIfNeeded()
        let updated = try retained(records, limits: limits, now: now)
        if updated != records { try save(updated); try removeOrphans() }
        return records.sorted { $0.copiedAt > $1.copiedAt }
    }
    @discardableResult
    public func insert(_ payload: ClipboardPayload, title: String, searchableText: String,
                       kind: ClipboardHistoryRecord.Kind, sourceBundleID: String?, sourceName: String?,
                       limits: ClipboardHistoryLimits = .init(), now: Date = Date()) throws -> [ClipboardHistoryRecord] {
        try loadIfNeeded()
        guard !payload.items.isEmpty, payload.items.allSatisfy({ !$0.representations.isEmpty }) else { throw ClipboardHistoryError.empty }
        guard payload.byteCount <= limits.itemBytes, payload.items.count <= 64,
              payload.items.allSatisfy({ $0.representations.count <= 16 }) else { throw ClipboardHistoryError.tooLarge }
        let id = payload.fingerprint
        var updated = records
        if let index = updated.firstIndex(where: { $0.id == id }) {
            updated[index].copiedAt = now
            updated[index].sourceBundleID = sourceBundleID
            updated[index].sourceName = sourceName
        } else {
            let encoder = PropertyListEncoder(); encoder.outputFormat = .binary
            let data = try encoder.encode(payload)
            guard data.count <= limits.diskBytes, data.count <= payloadLimit else { throw ClipboardHistoryError.tooLarge }
            let record = ClipboardHistoryRecord(id: id, kind: kind, title: String(title.prefix(500)),
                searchableText: String(searchableText.prefix(8_192)), sourceBundleID: sourceBundleID,
                sourceName: sourceName, copiedAt: now, favorite: false, byteCount: payload.byteCount,
                storedBytes: data.count, itemCount: payload.items.count)
            updated.append(record)
            // Compute quotas before changing either the current index or payload files.
            updated = try retained(updated, limits: limits, now: now)
            guard updated.contains(where: { $0.id == id }) else { throw ClipboardHistoryError.favoritesFillQuota }
            try data.write(to: payloadURL(id), options: .atomic)
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: payloadURL(id).path)
        }
        try save(try retained(updated, limits: limits, now: now))
        try removeOrphans()
        return records
    }
    public func payload(id: String) throws -> ClipboardPayload {
        try loadIfNeeded()
        guard validID(id), let record = records.first(where: { $0.id == id }),
              record.storedBytes > 0, record.storedBytes <= payloadLimit,
              (try? payloadURL(id).resourceValues(forKeys: [.fileSizeKey]).fileSize) == record.storedBytes else {
            throw ClipboardHistoryError.missing
        }
        let payload: ClipboardPayload
        do {
            let data = try readBounded(payloadURL(id), maxBytes: record.storedBytes)
            guard data.count == record.storedBytes else { throw ClipboardHistoryError.missing }
            payload = try PropertyListDecoder().decode(ClipboardPayload.self, from: data)
        }
        catch { throw ClipboardHistoryError.missing }
        guard payload.fingerprint == id else { throw ClipboardHistoryError.missing }
        return payload
    }
    public func setFavorite(id: String, value: Bool) throws -> [ClipboardHistoryRecord] {
        try loadIfNeeded()
        var updated = records
        guard let index = updated.firstIndex(where: { $0.id == id }) else { throw ClipboardHistoryError.missing }
        updated[index].favorite = value
        try save(updated)
        return records
    }
    public func delete(id: String) throws -> [ClipboardHistoryRecord] {
        try loadIfNeeded(); try save(records.filter { $0.id != id }); try removeOrphans(); return records
    }
    /// Only an explicit, confirmed user action bypasses index decoding. A malformed index cannot
    /// permanently prevent recovery, while ordinary loads never overwrite the original evidence.
    public func clear() throws {
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true,
                                                 attributes: [.posixPermissions: 0o700])
        try save([])
        loaded = true
        try removeOrphans()
    }
}
